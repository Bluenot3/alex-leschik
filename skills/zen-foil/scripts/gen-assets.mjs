#!/usr/bin/env node
/**
 * Inlines the binary assets (world map mask, brand masks, DM Mono subset)
 * into src/assets.ts as base64, so the engine needs no asset pipeline and
 * makes no network requests of its own.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const b64 = (f) => readFileSync(join(root, "assets", f)).toString("base64");

const out = `/* Generated by scripts/gen-assets.mjs — do not edit. */

/** World land mask, equirectangular 1024 × 512 (Natural Earth 1:50m, public domain). */
export const WORLD_PNG = "data:image/png;base64,${b64("world-land.png")}";
/** ZEN mark coverage mask, 256 × 256. */
export const ZEN_PNG = "data:image/png;base64,${b64("logo-zen.png")}";
/** Boys & Girls Clubs hands mark coverage mask, 256 × 256. */
export const BGC_PNG = "data:image/png;base64,${b64("logo-bgc.png")}";
/** DM Mono Regular, subset to the atlas glyphs (SIL OFL 1.1, LICENSES/DMMono-OFL.txt). */
export const MONO_WOFF2 = "${b64("dm-mono-subset.woff2")}";
`;
writeFileSync(join(root, "src", "assets.ts"), out);
console.log(`src/assets.ts: ${(out.length / 1024).toFixed(1)} KB`);
